-- STEP 2. 데이터 모델 ----------------------------------------------------

create table if not exists public.regions (
    region_code text primary key,
    region_name text not null unique,
    center_lat double precision,
    center_lng double precision,
    created_at timestamptz not null default now()
);

create table if not exists public.naver_trend (
    id bigint generated by default as identity primary key,
    reference_date date not null,
    keyword text not null,
    ratio numeric not null,
    collected_at timestamptz not null default now(),
    unique (reference_date, keyword)
);

-- region_code: 관광공사 시군구 코드(signguCd). 시도 집계는 아래 View
create table if not exists public.tourism_demand (
    id bigint generated by default as identity primary key,
    reference_date date not null,
    region_code text not null,
    stay_strength numeric,
    consumption_strength numeric,
    collected_at timestamptz not null default now(),
    unique (reference_date, region_code)
);

create table if not exists public.local_places (
    id bigint generated by default as identity primary key,
    place_key text not null unique,
    region_code text,
    search_category text not null,
    name text not null,
    category text,
    address text,
    road_address text,
    longitude double precision,
    latitude double precision,
    source_link text,
    collected_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.ai_region_analysis (
    id bigint generated by default as identity primary key,
    analysis_date date not null,
    region_code text not null,
    summary text not null,
    limitations text,
    llm_provider text,
    model_name text,
    created_at timestamptz not null default now(),
    unique (analysis_date, region_code)
);

create table if not exists public.collection_runs (
    run_id text primary key,
    source text not null,
    started_at timestamptz not null,
    finished_at timestamptz,
    status text not null,
    row_count integer not null default 0,
    error_message text,
    created_at timestamptz not null default now()
);

-- STEP 3. RLS: 읽기만 허용 -------------------------------------------------

do $$
declare t text;
begin
  foreach t in array array['regions','naver_trend','tourism_demand','local_places','ai_region_analysis','collection_runs'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', 'public read ' || t, t);
    execute format('create policy %I on public.%I for select using (true)', 'public read ' || t, t);
  end loop;
end $$;

-- 분석용 View ----------------------------------------------------------------

-- 시군구 → 시도 월별 평균 (시군구 코드 앞 2자리 = 시도 코드)
-- ponytail: 시군구 단순 평균. 인구/면적 가중이 필요하면 여기서 바꿀 것
create or replace view public.region_tourism_monthly with (security_invoker = on) as
select t.reference_date, r.region_code, r.region_name,
       avg(t.stay_strength)        as stay_strength,
       avg(t.consumption_strength) as consumption_strength,
       count(*)                    as signgu_count
from public.tourism_demand t
join public.regions r on r.region_code = left(t.region_code, 2)
group by t.reference_date, r.region_code, r.region_name;

-- 지역별 최신 월 + 지도 좌표 + 최신 AI 분석
create or replace view public.region_latest with (security_invoker = on) as
select distinct on (m.region_code)
       m.*, r.center_lat, r.center_lng, a.summary, a.limitations, a.analysis_date
from public.region_tourism_monthly m
join public.regions r on r.region_code = m.region_code
left join lateral (
    select x.summary, x.limitations, x.analysis_date
    from public.ai_region_analysis x
    where x.region_code = m.region_code
    order by x.analysis_date desc
    limit 1
) a on true
order by m.region_code, m.reference_date desc;

-- Make Scenario 2가 반복 호출할 시군구 목록 (실제로 데이터가 있었던 코드만)
create or replace view public.signgu_list with (security_invoker = on) as
select distinct left(region_code, 2) as area_code, region_code as signgu_code
from public.tourism_demand
order by signgu_code;
